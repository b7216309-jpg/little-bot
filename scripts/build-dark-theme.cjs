'use strict';
// Generates src/renderer/dark.css from the light stylesheets: every rule that sets a color gets a
// dark twin under html[data-theme=dark]. Lightness is mirrored (paper becomes charcoal, ink becomes
// paper) while hue is kept, so the palette and accents stay recognizable. Run after editing CSS:
//   node scripts/build-dark-theme.cjs
const fs = require('node:fs');
const path = require('node:path');

const renderer = path.join(__dirname, '..', 'src', 'renderer');
const SOURCES = ['styles.css', 'goal-ledger.css', 'provider-usage.css', 'standing-intents.css', 'branding.css'];
const OUTPUT = path.join(renderer, 'dark.css');
const SKIP_PROPERTIES = /^(box-shadow|text-shadow|filter|-webkit-app-region|mask|content)$/;
const COLOR = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|(?<![-\w])(?:white|black)(?![-\w])/g;

function parseColor(token) {
  if (token === 'white') return [255, 255, 255, 1];
  if (token === 'black') return [0, 0, 0, 1];
  if (token.startsWith('#')) {
    let hex = token.slice(1);
    if (hex.length === 3 || hex.length === 4) hex = [...hex].map(char => char + char).join('');
    if (hex.length !== 6 && hex.length !== 8) return null;
    const value = [0, 2, 4].map(index => parseInt(hex.slice(index, index + 2), 16));
    return [...value, hex.length === 8 ? parseInt(hex.slice(6, 8), 16) / 255 : 1];
  }
  const parts = token.replace(/rgba?\(|\)/g, '').split(/[\s,/]+/).filter(Boolean).map(Number);
  if (parts.length < 3 || parts.some(Number.isNaN)) return null;
  return [parts[0], parts[1], parts[2], parts.length > 3 ? parts[3] : 1];
}
function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h / 6, s, l];
}
function fromHsl([h, s, l]) {
  if (!s) return [l, l, l].map(value => Math.round(value * 255));
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q;
  const channel = t => { t = (t + 1) % 1; return t < 1 / 6 ? p + (q - p) * 6 * t : t < 1 / 2 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p; };
  return [channel(h + 1 / 3), channel(h), channel(h - 1 / 3)].map(value => Math.round(value * 255));
}
// Mirror lightness into a dark range; keep strong accents near their own lightness.
function darken(token) {
  const color = parseColor(token);
  if (!color) return token;
  const [h, s, l] = toHsl(color);
  let next;
  if (s > 0.35 && l > 0.3 && l < 0.7) next = [h, s * 0.85, Math.min(0.68, l + 0.08)];
  else next = [h, Math.min(s, 0.12), 0.1 + (1 - l) * 0.86];
  const [r, g, b] = fromHsl(next);
  const alpha = color[3];
  return alpha < 1 ? `rgba(${r},${g},${b},${+alpha.toFixed(3)})` : `#${[r, g, b].map(value => value.toString(16).padStart(2, '0')).join('')}`;
}

// Minimal CSS walker for the app's own stylesheets (flat rules plus @media / @supports blocks).
function walk(css, emit, prefix = '') {
  let index = 0;
  while (index < css.length) {
    const open = css.indexOf('{', index);
    if (open < 0) break;
    const head = css.slice(index, open).trim();
    if (head.startsWith('@media') || head.startsWith('@supports')) {
      let depth = 1, cursor = open + 1;
      while (cursor < css.length && depth) { if (css[cursor] === '{') depth++; else if (css[cursor] === '}') depth--; cursor++; }
      const inner = [];
      walk(css.slice(open + 1, cursor - 1), rule => inner.push(rule));
      if (inner.length) emit(`${head}{${inner.join('')}}`);
      index = cursor;
      continue;
    }
    const close = css.indexOf('}', open);
    if (head.startsWith('@')) { index = close + 1; continue; }
    const body = css.slice(open + 1, close);
    const declarations = body.split(';').map(item => item.trim()).filter(Boolean).flatMap(item => {
      const colon = item.indexOf(':');
      if (colon < 0) return [];
      const property = item.slice(0, colon).trim(), value = item.slice(colon + 1).trim();
      if (SKIP_PROPERTIES.test(property) || !COLOR.test(value)) return [];
      COLOR.lastIndex = 0;
      return [`${property}:${value.replace(COLOR, darken)}`];
    });
    if (declarations.length) {
      const selector = head.split(',').map(item => {
        const part = item.trim();
        if (part === ':root' || part === 'html') return 'html[data-theme=dark]';
        return `html[data-theme=dark] ${part}`;
      }).join(',');
      emit(`${selector}{${declarations.join(';')}}`);
    }
    index = close + 1;
  }
}

function build() {
  const rules = [];
  for (const file of SOURCES) {
    const css = fs.readFileSync(path.join(renderer, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
    walk(css, rule => rules.push(rule));
  }
  return '/* Generated by scripts/build-dark-theme.cjs from the light stylesheets. Do not edit by hand. */\n'
    + 'html[data-theme=dark]{color-scheme:dark}\n' + rules.join('\n') + '\n';
}
if (require.main === module) {
  const output = build();
  fs.writeFileSync(OUTPUT, output);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}.`);
}
module.exports = { build, darken, OUTPUT };
